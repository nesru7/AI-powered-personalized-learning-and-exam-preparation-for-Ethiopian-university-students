type LanguageContextValue = {
  language: Language
  setLanguage: (language: Language) => void
  t: (key: string, values?: Record<string, string>) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)
const STORAGE_KEY = 'ethiolearn-language'

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>('en')

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY)
    if (stored && LANGUAGES.includes(stored as Language)) {
      setLanguageState(stored as Language)
    }
  }, [])

  useEffect(() => {
    document.documentElement.lang = language === 'am' ? 'am' : language === 'om' ? 'om' : 'en'
  }, [language])

  const setLanguage = useCallback((next: Language) => {
    window.localStorage.setItem(STORAGE_KEY, next)
    setLanguageState(next)
  }, [])

  const t = useCallback((key: string, values?: Record<string, string>) => {
    const dictionary = translations[language] as Record<string, string>
    const fallback = translations.en as Record<string, string>
    let value = dictionary[key] ?? fallback[key] ?? key

    for (const [name, replacement] of Object.entries(values ?? {})) {
      value = value.replace(`{${name}}`, replacement)
    }
    return value
  }, [language])

  return <LanguageContext.Provider value={{ language, setLanguage, t }}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used within LanguageProvider')
  return context
}

export function T({ id, values }: { id: string; values?: Record<string, string> }) {
  const { t } = useLanguage()
  return <>{t(id, values)}</>
}
